import re
import pandas as pd

from data.duckdb_manager import DuckDBManager
from guardrails.tool_guardrails import validate_query

class SQLTool:
    def __init__(self, df:pd.DataFrame):

        self.db = DuckDBManager() 

        self.db.register_dataframe(
            df,
            table_name="data"
        )

    def execute(self, query: str) -> pd.DataFrame:

        query = self.clean_query(query)
        print(f"SQL query: {query}")  # Debugging statement
        validate_query(query)
        

        return self.db.execute_query(query)

    @staticmethod
    def clean_query(query: str) -> str:
        query = re.sub(r"```sql", "", query, flags=re.IGNORECASE) # To remove unwanted symbols and words generated by LLM.
        query = query.replace("```", "") # Replace with "".
        return query.strip() # Return clean sql query.

